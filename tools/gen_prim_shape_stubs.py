#!/usr/bin/env python3
"""Write the stub file for the prim shape oracle from what the link actually needs.

Nothing here is invented: the list comes from nm on the two object files, minus whatever the real
translation unit already provides. Each symbol is written as an extern "C" definition under its
exact mangled name, and every one of them aborts if it is ever called - the Set* path the check
runs does not reach any of them, so a stub being hit is a bug in the check, not a passing result.

Two kinds of symbol are listed separately and the check reports them separately:
  - functions whose body is not in this tree (declared in a header, never defined),
  - globals with no definition in this tree.

Usage: python3 tools/gen_prim_shape_stubs.py
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OBJ = os.path.join(ROOT, 'build', 'prim_shape')
NM = 'nm'

PREFIX_SKIP = ('_ZSt', '_ZTV', '_ZTI', '_ZTS', '__cxa', '__gxx', '_Zdl', '_Zda', '_Zna',
               '__stack', '_Unwind', '_ZN10__cxxabiv', '_ZNK10__cxxabiv')

# Not stubbed here because the harness supplies a labelled host-side definition instead.
HOST_SIDE = {'_ZN9PblMatrixC1ERK10PblVector4S2_S2_S2_':
             'spike/prim_shape_host.cpp - needed by this TU file-scope initializer, '
             'never read by the measured path'}


def undefined(path):
    if not os.path.exists(path):
        return set()
    out = subprocess.run([NM, '-u', path], capture_output=True, text=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[0] == 'U':
            n = parts[1]
            # C symbols (memcpy, sqrtf, ...) come from libc. Only mangled C++ names are ours.
            if n.startswith('_ZN') and not n.startswith(PREFIX_SKIP):
                names.add(n)
    return names


def defined(path):
    if not os.path.exists(path):
        return set()
    out = subprocess.run([NM, path], capture_output=True, text=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in ('T', 'B', 'D', 'R'):
            names.add(parts[2])
    return names


def is_data(name):
    # _ZN<len><class><len><field>E is a variable; a function has type codes before the closing E.
    body = name[len('_ZN'):]
    m = re.match(r'(\d+)([a-zA-Z_]+)(\d+)([a-zA-Z_]+)E$', body)
    return bool(m)


def main():
    need = undefined(os.path.join(OBJ, 'CollisionPrimitive.o'))
    provided = defined(os.path.join(OBJ, 'CollisionUtil.o'))
    stubs = need - provided
    out_path = os.path.join(ROOT, 'spike', 'prim_shape_stubs.cpp')

    lines = [
        '// Generated by tools/gen_prim_shape_stubs.py - do not hand-edit.',
        '//',
        '// Only symbols the link needs. The check calls SetSphere/SetCylinder/SetBox, which reach',
        '// none of these. Each one aborts, so if the check ever prints one of these names, the path',
        '// the check measured was not the path this file claims to measure.',
        '//',
        '// Satisfied by real code, not stubbed here:',
    ]
    for name in sorted(provided & need):
        lines.append('//   %s' % name)
    lines.append('')
    lines.append('// Provided by the harness as host-side, not stubbed here:')
    for name in sorted(HOST_SIDE):
        lines.append('//   %s  <- %s' % (name, HOST_SIDE[name]))

    funcs = sorted(n for n in stubs if not is_data(n) and n not in HOST_SIDE)
    data = sorted(n for n in stubs if is_data(n))

    lines += ['', '#include <cstdio>', '#include <cstdlib>', '',
            'extern "C" {', '', '// no body in this tree (declared only)', '']
    for n in funcs:
        lines.append('void %s(void) { fputs("stub called: %s\\n", stderr); abort(); }' % (n, n))
    lines.append('')
    for n in data:
        lines.append('int %s = 0;   /* no definition in this tree */' % n)
    lines.append('}')

    open(out_path, 'w').write('\n'.join(lines) + '\n')
    print('wrote %s: %d functions with no body in this tree, %d globals with no definition'
          % (out_path, len(funcs), len(data)))
    print('satisfied by linking CollisionUtil.o:', sorted(need - stubs) or 'nothing')


if __name__ == '__main__':
    sys.exit(main())
